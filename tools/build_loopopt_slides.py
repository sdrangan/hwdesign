def code(ids, x, y, w, src, sz=12, inset=0.16):
    """A code box sized to its lines."""
    n = len(src.strip("\n").split("\n"))
    h = 2 * inset + n * sz * 1.22 / 72
    return kit.code_box(ids, x, y, w, h, src, sz=sz, inset=inset)


def portal_caption(ids, qtag):
    return label(ids, L, 6.2, 9.0, 0.32, f"Also in the LLM grader: Unit 7 › {qtag}", sz=12)


def homework(ids, qtag):
    return label(ids, L, 6.2, W, 0.32, f"Homework in the LLM grader: Unit 7 › {qtag}", sz=12)


def col(ids, x, w, items, y=1.75, h=4.4, sz=18, sub=15):
    """A bullet column: strings are level 1, ("-", text) level 2."""
    paras = []
    for k, it in enumerate(items):
        if isinstance(it, tuple):
            paras.append(b2(it[1], sz=sub, spcBef=3))
        else:
            paras.append(b1(it, sz=sz, spcBef=0 if k == 0 else 10))
    return textbox(ids, x, y, w, h, paras)


def band(ids, text, y=5.75, h=0.62, sz=16):
    return shape(ids, L, y, W, h, fill=TINT, line=VIOLET, lw=1.25,
                 paras=[para(text, sz=sz, color=TEXT, align="ctr")])


def errcard(ids, x, y, w, h, title, lines, sz=14):
    return card(ids, x, y, w, h, fill=AMBERTINT, paras=[para(f"^^{title}^^", sz=15, spcAft=4)] +
                [para(t, sz=sz, color=TEXT, spcAft=3) for t in lines])


def ctr(rows):
    """Centre every cell of a table given as lists of strings."""
    return [[c if isinstance(c, dict) else {"t": c, "align": "ctr"} for c in r] for r in rows]


