# --------------------------------------------------------------- pictures ---
_PENDING = {}


def _fig_path(fig):
    if "/" in fig:
        pre, name = fig.split("/", 1)
        return FIG_DIRS[pre] / f"{name}.png"
    return FIGS / f"{fig}.png"


def pic(ids, fig, x, y, w, h, align="c"):
    """A figure, scaled to fit the box (x, y, w, h) and centred in it (align
    "l" keeps it at the left edge, "t" at the top only).  "u6/name" and
    "docs/name" are unit 6's figures and the demo's docs images."""
    path = _fig_path(fig)
    if not path.exists():
        raise SystemExit(f"missing {path}: run units/unit07_loopopt/figs/make_figs.py first")
    with Image.open(path) as im:
        aspect = im.width / im.height
    pw, ph = (w, w / aspect) if w / aspect <= h else (h * aspect, h)
    px = x if align == "l" else x + (w - pw) / 2
    py = y if align in ("l", "t") else y + (h - ph) / 2
    token = f"@@RID:{fig}@@"
    _PENDING[token] = path
    i = ids()
    return (f'<p:pic><p:nvPicPr><p:cNvPr id="{i}" name="Picture {i}" descr="{path.stem}"/>'
            f'<p:cNvPicPr><a:picLocks noChangeAspect="1"/></p:cNvPicPr><p:nvPr/></p:nvPicPr>'
            f'<p:blipFill><a:blip r:embed="{token}"/><a:stretch><a:fillRect/></a:stretch></p:blipFill>'
            f'<p:spPr><a:xfrm><a:off x="{E(px)}" y="{E(py)}"/><a:ext cx="{E(pw)}" cy="{E(ph)}"/></a:xfrm>'
            f'<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr></p:pic>')


def _attach_pictures(slide, xml):
    relp = SLIDES / "_rels" / f"{slide}.rels"
    rels = relp.read_text(encoding="utf-8")
    for token in sorted(set(re.findall(r"@@RID:[^@]+@@", xml))):
        fig = token[len("@@RID:"):-2]
        src = _PENDING[token]
        media = BUILD / "ppt" / "media" / f"u7_{fig.replace('/', '_')}.png"
        media.write_bytes(src.read_bytes())
        n = max([int(k) for k in re.findall(r'Id="rId(\d+)"', rels)] + [0]) + 1
        rels = rels.replace(
            "</Relationships>",
            f'<Relationship Id="rId{n}" Type="http://schemas.openxmlformats.org/officeDocument/2006/'
            f'relationships/image" Target="../media/{media.name}"/></Relationships>')
        xml = xml.replace(token, f"rId{n}")
    relp.write_text(rels, encoding="utf-8")
    return xml


def write(slide, shapes):
    xml = _attach_pictures(slide, kit.slide_doc(shapes))
    (SLIDES / slide).write_text(xml, encoding="utf-8")
    kit.drop_unused_rels(slide)


