def restyle_textboxes(slide):
    """kit.restyle rewrites the body placeholder's list style.  Some kept slides
    (the propagation-delay tables) carry the master's hollow-square bullets in a
    text box's own list style instead; give those the same violet squares and
    grey dashes, and the old accent-tinted panels unit 5's violet tint."""
    p = SLIDES / slide
    t = p.read_text(encoding="utf-8")
    t = re.sub(r'<a:buSzPct val="100000"/><a:buFont typeface="Wingdings"[^>]*/><a:buChar char="q"/>',
               '<a:buSzPct val="70000"/><a:buFont typeface="Arial"/><a:buChar char="■"/>', t)
    t = re.sub(r'<a:buClr><a:schemeClr val="accent1"/></a:buClr><a:buFont typeface="Calibri"[^>]*/>'
               r'<a:buChar char="◦"/>',
               '<a:buClr><a:srgbClr val="999999"/></a:buClr><a:buFont typeface="Arial"/>'
               '<a:buChar char="–"/>', t)
    t = t.replace('<a:schemeClr val="accent1"><a:lumMod val="20000"/><a:lumOff val="80000"/>'
                  '</a:schemeClr>', f'<a:srgbClr val="{TINT}"/>')
    p.write_text(t, encoding="utf-8")


def main():
    global FIGS, BUILD, SLIDES
    args = _parse_args()
    BUILD = (args.work / "unpacked").resolve()
    SLIDES = BUILD / "ppt" / "slides"
    FIGS = args.figs.resolve()
    kit.BUILD, kit.SLIDES = BUILD, SLIDES       # the shared helpers read these
    scripts = args.skill_scripts

    if BUILD.exists():
        shutil.rmtree(BUILD)
    zipfile.ZipFile(args.src).extractall(BUILD)

    order = kit.slide_order()
    titles = [kit.slide_title(n) for n in order]
    if MIGRATED_MARKER in titles and not args.force:
        raise SystemExit(f"{args.src.name} already contains {MIGRATED_MARKER!r}: it has been "
                         "through this script.  This is a one-shot migration; see the docstring.")
    for pos, want in EXPECTED.items():
        got = titles[pos - 1]
        if got.strip() != want.strip():
            raise SystemExit(f"expected {want!r} at position {pos}, found {got!r}")
    old = {k + 1: n for k, n in enumerate(order)}

    # 1. structure, before any content edit: new slides duplicate a donor that
    # has only its layout relationship ("Title and Content"), then the final
    # order is written in one go.
    donor = old[2]
    assert (SLIDES / "_rels" / f"{donor}.rels").read_text(encoding="utf-8").count("<Relationship ") == 1
    final, jobs = [], []
    for item in PLAN:
        if item[0] == "old":
            _, pos, fn = item
            final.append(old[pos])
            if fn:
                jobs.append((old[pos], fn))
        else:
            made = kit.sh([sys.executable, "add_slide.py", str(BUILD), donor], cwd=scripts)
            name = re.search(r"Created ppt/slides/(slide\d+\.xml)", made).group(1)
            final.append(name)
            jobs.append((name, item[1]))
    kit.set_order(final)
    kept = [n for n in final if n not in {s for s, _ in jobs}]
    n_new = sum(1 for i in PLAN if i[0] == "new")
    print(f"{len(final)} slides: {len(jobs)} built, {len(kept)} kept, "
          f"{len(order) - (len(final) - n_new)} old dropped")

    # 2. content
    for name, fn in jobs:
        write(name, fn(Ids()))

    # 3. fixes and restyle on the kept slides
    text_fixes(old)
    kit.retheme_accent1()
    for name in kept:
        kit.restyle(name)
        kit.recolour_diagrams(name)
        restyle_textboxes(name)

    # 4. pack
    print(kit.sh([sys.executable, "clean.py", str(BUILD)], cwd=scripts).strip())
    kit.pack(args.out)
    print("wrote", args.out)


if __name__ == "__main__":
    main()
